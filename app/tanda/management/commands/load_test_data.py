class Command(BaseCommand):
    help = 'Загружает данные тестов в базу'

    def handle(self, *args, **options):
        # Очистка старых данных (опционально)
        # Question.objects.all().delete()

        for test_item in TEST_DATA:
            question_text = test_item["question"]
            
            # Создаем или получаем вопрос
            question, created = Question.objects.get_or_create(text=question_text)
            
            if created:
                self.stdout.write(self.style.SUCCESS(f'✓ Создан вопрос: {question_text[:50]}...'))
            
            # Создаем опции
            for option_data in test_item["options"]:
                Option.objects.get_or_create(
                    question=question,
                    value=option_data["val"],
                    defaults={
                        'text': option_data["text"],
                        'skill1': option_data.get("cr", 0),  # Креативность
                        'skill2': option_data.get("vi", 0),  # Визуальное мышление
                        'skill3': option_data.get("lo", 0),  # Логика
                        'skill4': option_data.get("an", 0),  # Аналитика
                        'skill5': option_data.get("or", 0),  # Организация
                        'skill6': option_data.get("st", 0),  # Структурирование
                    }
                )
                self.stdout.write(f'  → Опция {option_data["val"]}: {option_data["text"][:40]}...')
        
        self.stdout.write(self.style.SUCCESS('✓ Все тесты загружены!'))
