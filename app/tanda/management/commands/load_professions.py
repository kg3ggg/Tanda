class Command(BaseCommand):
    help = 'Загружает данные профессий с изображениями в базу'

    def handle(self, *args, **options):
        static_professions_dir = Path(__file__).resolve().parent.parent.parent.parent.parent / 'tanda' / 'static' / 'professions'
        
        for prof_data in PROFESSIONS_DATA:
            profession, created = Profession.objects.get_or_create(
                title=prof_data["title"],
                defaults={
                    "skill": prof_data["skill"],
                    "reason": prof_data.get("reason", ""),
                    "description": prof_data.get("description", ""),
                }
            )
            
            # Загружаем изображение, если оно существует и еще не загружено
            image_filename = prof_data.get("image")
            if image_filename and not profession.image:
                image_path = static_professions_dir / image_filename
                if image_path.exists():
                    try:
                        with open(image_path, 'rb') as img_file:
                            profession.image.save(
                                image_filename,
                                ContentFile(img_file.read()),
                                save=True
                            )
                        self.stdout.write(self.style.SUCCESS(f'✓ Загружено изображение для: {profession.title}'))
                    except Exception as e:
                        self.stdout.write(self.style.ERROR(f'✗ Ошибка загрузки изображения для {profession.title}: {str(e)}'))
                else:
                    self.stdout.write(self.style.WARNING(f'⚠ Изображение не найдено: {image_path}'))
            
            if created:
                self.stdout.write(self.style.SUCCESS(f'✓ Создана профессия: {profession.title}'))
            else:
                # Обновляем существующую профессию
                updated = False
                if profession.skill != prof_data["skill"]:
                    profession.skill = prof_data["skill"]
                    updated = True
                if profession.reason != prof_data.get("reason", ""):
                    profession.reason = prof_data.get("reason", "")
                    updated = True
                if profession.description != prof_data.get("description", ""):
                    profession.description = prof_data.get("description", "")
                    updated = True
                
                if updated:
                    profession.save()
                    self.stdout.write(self.style.WARNING(f'⟳ Обновлена профессия: {profession.title}'))

        self.stdout.write(self.style.SUCCESS('✓ Загрузка профессий завершена'))
