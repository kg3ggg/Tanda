class Command(BaseCommand):
    help = 'Загружает данные профессий в базу'

    def handle(self, *args, **options):
        # Очистка старых данных (опционально)
        # Profession.objects.all().delete()

        for prof_data in PROFESSIONS_DATA:
            profession, created = Profession.objects.get_or_create(
                title=prof_data["title"],
                skill=prof_data["skill"],
                defaults={
                    'reason': prof_data["reason"],
                    'description': prof_data["description"],
                }
            )
            
            if created:
                self.stdout.write(self.style.SUCCESS(f'✓ Создана профессия: {prof_data["title"]}'))
            else:
                self.stdout.write(f'→ Профессия уже существует: {prof_data["title"]}')
        
        self.stdout.write(self.style.SUCCESS('✓ Все профессии загружены!'))
